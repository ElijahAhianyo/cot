const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.argv[2] || 'http://127.0.0.1:18080/guide/master/';
const artifacts = process.env.DOCS_ARTIFACTS || '/tmp/cot-docs-preview';
fs.mkdirSync(artifacts, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, colorScheme: 'light' });
  // Font CDN availability must not determine whether local navigation works.
  await page.route(/https:\/\/(fonts\.googleapis\.com|fonts\.gstatic\.com)/, route => route.abort());
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  assert.equal(await page.locator('article h1').textContent(), 'Cot documentation');
  assert.equal(await page.locator('article h2#start-with-what-you-need').count(), 1);
  const sidebar = page.locator('aside .d-none.d-lg-block');
  assert.equal(await sidebar.locator('.doc-section-link.active').count(), 1);
  await page.screenshot({ path: artifacts + '/home-desktop.png', fullPage: true });
  assert.equal(await page.locator('.guide-chapters a[href*="blog/"]').count(), 0);
  await page.locator('.navbar').getByRole('link', { name: 'Blog', exact: true }).click();
  await page.waitForURL('**/blog/overview/');
  assert.equal(await page.locator('.navbar a.active').textContent(), 'Blog');
  await page.locator('article').getByRole('link', { name: 'Why framework transition guides belong in the docs', exact: true }).click();
  await page.waitForURL('**/blog/framework-transition-guides/');
  assert.equal(await page.locator('nav[aria-label="Tutorial sequence"]').count(), 0);
  for (const framework of ['django', 'laravel', 'rails', 'spring-boot', 'axum', 'actix-web']) {
    await page.goto(base + 'coming-from/' + framework + '/');
    assert.equal((await page.locator('.doc-page-kind').textContent()).trim(), 'Explanation');
    assert.equal(await sidebar.locator('a[aria-current="page"]').count(), 1);
  }
  await page.screenshot({ path: artifacts + '/transition-desktop.png', fullPage: true });
  await page.goto(base);

  await sidebar.getByRole('link', { name: 'Guides', exact: true }).click();
  await page.waitForURL('**/guides/overview/');
  assert.equal(await sidebar.locator('details').count(), 0);
  await sidebar.getByRole('combobox', { name: 'Jump to topic' }).selectOption('Requests and responses');
  await sidebar.getByRole('link', { name: /^Requests and extractors/ }).click();
  await page.waitForURL('**/guides/requests/');
  assert.equal(await sidebar.locator('a[aria-current="page"]').count(), 1);
  assert.equal((await page.locator('.doc-page-kind').textContent()).trim(), 'Explanation');
  assert.equal(await page.locator('nav[aria-label="Tutorial sequence"]').count(), 0);
  assert.match(await page.locator('.doc-breadcrumbs').textContent(), /Requests and responses/);
  await page.screenshot({ path: artifacts + '/guide-desktop.png', fullPage: true });
  await page.goto(base + 'guides/background-tasks/', { waitUntil: 'domcontentloaded' });
  assert.match(await page.locator('.doc-preview-note').textContent(), /not currently supported/);
  await page.screenshot({ path: artifacts + '/proposed-desktop.png', fullPage: true });
  await page.goto(base + 'tutorials/model/');
  assert.equal(await page.locator('a[rel="prev"]').count(), 1);
  assert.equal(await page.locator('a[rel="next"]').count(), 1);
  await page.goto(base + 'tutorials/test-deploy/');
  assert.equal(await page.locator('a[rel="next"]').count(), 0);
  await page.goto(base + 'reference/overview/');
  assert(await page.locator('article a[href="https://docs.rs/cot/latest/cot/"]').count() > 0);
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.keyboard.press('/');
  assert(await page.locator('#cot-search').evaluate(el => el === document.activeElement));
  await page.locator('#cot-search').fill('idempotency');
  await page.locator('#search-results-list h3 a').first().waitFor();
  assert.match(await page.locator('#search-results-list').textContent(), /Proposed/);
  await page.screenshot({ path: artifacts + '/search-desktop.png', fullPage: true });
  await page.locator('#search-close').click();
  assert(await page.locator('article').isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: artifacts + '/home-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Toggle guide navigation' }).click();
  const mobile = page.locator('#cot-guide-chapters');
  await mobile.locator(':scope.show:not(.showing)').waitFor();
  await mobile.getByRole('link', { name: 'Guides', exact: true }).click();
  await page.waitForURL('**/guides/overview/');
  await page.getByRole('button', { name: 'Toggle guide navigation' }).click();
  await mobile.locator(':scope.show:not(.showing)').waitFor();
  await mobile.getByRole('combobox', { name: 'Jump to topic' }).selectOption('Application services');
  assert.equal(await mobile.locator('details').count(), 0);
  await page.screenshot({ path: artifacts + '/navigation-mobile.png' });
  await mobile.getByRole('link', { name: /^Background tasks/ }).click();
  await page.waitForURL('**/guides/background-tasks/');
  assert(await page.locator('article h1').isVisible());
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.getByRole('button', { name: 'On this page' }).click();
  assert(await page.locator('#page-toc').isVisible());
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.screenshot({ path: artifacts + '/guide-dark-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Toggle guide navigation' }).click();
  await mobile.locator(':scope.show:not(.showing)').waitFor();
  await page.screenshot({ path: artifacts + '/navigation-dark-mobile.png' });
  await page.keyboard.press('Escape');
  await mobile.waitFor({ state: 'hidden' });
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(base + 'guides/requests/', { waitUntil: 'domcontentloaded' });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Overflow at ' + width);
  }
  await page.goto(base.replace('/master/', '/v0.5/') + 'introduction/');
  assert(await sidebar.getByRole('link', { name: 'Templates', exact: true }).isVisible());
  assert.equal(await sidebar.locator('details').count(), 0);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('Desktop/mobile navigation, breadcrumbs, tutorial sequence, status labels, Rustdoc links, search, TOC, and overflow checks passed.');
})().catch(error => { console.error(error); process.exit(1); });
